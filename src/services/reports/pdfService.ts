import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface PdfReportOptions {
  title: string;
  subtitle?: string;
  generatedBy: string;
  organizationName?: string;
  columns: string[];
  rows: (string | number)[][];
  filename: string;
}

export function exportTableToPdf(options: PdfReportOptions): void {
  const doc = new jsPDF({
    orientation: options.columns.length > 5 ? 'landscape' : 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Header band
  doc.setFillColor(11, 25, 44); // Deep Navy
  doc.rect(0, 0, pageWidth, 68, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text('REXON MANAGEMENT APP', 36, 28);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(191, 219, 254);
  doc.text('Smart Security & Facility Management Platform', 36, 44);

  // Report title & metadata
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(options.title, 36, 98);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  const metaParts = [
    options.organizationName ? `Organization: ${options.organizationName}` : 'Global Platform Scope',
    `Generated By: ${options.generatedBy}`,
    `Exported: ${new Date().toLocaleString()}`,
  ];
  doc.text(metaParts.join('  |  '), 36, 114);

  if (options.subtitle) {
    doc.text(options.subtitle, 36, 128);
  }

  autoTable(doc, {
    startY: options.subtitle ? 142 : 130,
    head: [options.columns],
    body: options.rows,
    styles: {
      fontSize: 8.5,
      cellPadding: 6,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.5,
    },
    headStyles: {
      fillColor: [29, 78, 216], // Royal Blue
      textColor: [255, 255, 255],
      fontStyle: 'bold',
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 36, right: 36 },
  });

  doc.save(options.filename.endsWith('.pdf') ? options.filename : `${options.filename}.pdf`);
}
